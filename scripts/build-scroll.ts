// Bakes content/scroll/darkwizscroll.html into lib/scroll/html.ts so /scroll serves it without file tracing.
// Runs automatically before `npm run build` (prebuild). Edit the .html, never the generated .ts.
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
const root = join(__dirname, "..");
const html = readFileSync(join(root, "content/scroll/darkwizscroll.html"), "utf8");
writeFileSync(join(root, "lib/scroll/html.ts"), `// GENERATED by scripts/build-scroll.ts from content/scroll/darkwizscroll.html: do not edit.\nexport const SCROLL_HTML: string = ${JSON.stringify(html)};\n`);
console.log(`scroll: ${(html.length / 1024).toFixed(0)} kB baked into lib/scroll/html.ts`);
